import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const promptRoot = path.join(repositoryRoot, 'browser-extension', 'prompt-library');
const outputPath = path.join(repositoryRoot, 'browser-extension', 'src', 'generated', 'prompt-catalog.js');

export async function walkPromptFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walkPromptFiles(absolute));
    else if (entry.isFile() && entry.name.endsWith('.md')) files.push(absolute);
  }
  return files;
}

export function parsePromptDocument(source, relativePath) {
  const metadata = parseMetadataTable(source);
  const id = requiredField(metadata, 'ID', relativePath).replaceAll('`', '').trim();
  if (!/^TB-PROMPT-(?:[A-Z0-9]+-)+\d{3}$/u.test(id)) {
    throw new Error(`Invalid canonical prompt ID in ${relativePath}: ${id}`);
  }

  const filename = path.posix.basename(relativePath);
  if (!filename.startsWith(`${id.toLowerCase()}-`)) {
    throw new Error(`Prompt filename does not match ID ${id}: ${relativePath}`);
  }

  const title = requiredField(metadata, 'Name', relativePath);
  const version = requiredField(metadata, 'Version', relativePath).replaceAll('`', '').trim();
  if (!/^\d+\.\d+\.\d+$/u.test(version)) {
    throw new Error(`Invalid semantic version in ${relativePath}: ${version}`);
  }

  return Object.freeze({
    id,
    title,
    version,
    status: requiredField(metadata, 'Status', relativePath),
    category: requiredField(metadata, 'Category', relativePath),
    tags: splitList(metadata.get('Tags')),
    dependencies: splitList(metadata.get('Dependencies')),
    compatibleProviders: splitList(metadata.get('Compatible Providers')),
    relatedPrompts: splitList(metadata.get('Related Prompts')),
    purpose: extractSectionLead(source, 'Purpose'),
    description: extractSectionLead(source, 'Description'),
    path: toExtensionPath(relativePath),
    routingIntents: splitList(metadata.get('Routing Intents')),
    negativeRoutingIntents: splitList(metadata.get('Negative Routing Intents')),
    workModes: normalizeModes(metadata.get('Work Modes')),
    routingRisk: String(metadata.get('Routing Risk') || 'standard').replaceAll('`', '').trim().toLowerCase(),
  });
}

export async function buildPromptCatalog(root = promptRoot) {
  const records = [];
  const ids = new Set();
  const paths = new Set();

  for (const absolutePath of await walkPromptFiles(root)) {
    const relativePath = path.relative(root, absolutePath).split(path.sep).join('/');
    const record = parsePromptDocument(await readFile(absolutePath, 'utf8'), relativePath);
    if (ids.has(record.id)) throw new Error(`Duplicate prompt ID: ${record.id}`);
    if (paths.has(record.path)) throw new Error(`Duplicate prompt source path: ${record.path}`);
    ids.add(record.id);
    paths.add(record.path);
    records.push(record);
  }

  records.sort((left, right) => left.id.localeCompare(right.id));
  return records;
}

export function renderPromptCatalog(records) {
  return `// Generated by scripts/generate-prompt-catalog.mjs. Do not edit manually.\nexport const GENERATED_PROMPT_CATALOG = Object.freeze(${JSON.stringify(records, null, 2)});\n`;
}

export function normalizeLineEndings(value) {
  return String(value).replace(/\r\n?/gu, '\n');
}

async function main() {
  const checkOnly = process.argv.includes('--check');
  const expected = renderPromptCatalog(await buildPromptCatalog());
  if (checkOnly) {
    const current = await readFile(outputPath, 'utf8').catch(() => '');
    if (normalizeLineEndings(current) !== normalizeLineEndings(expected)) {
      console.error('Generated prompt catalog is stale. Run pnpm run generate:prompts.');
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(outputPath, expected);
}

function parseMetadataTable(source) {
  const section = extractSection(source, 'Metadata');
  const metadata = new Map();
  for (const line of section.split(/\r?\n/u)) {
    const match = line.match(/^\|\s*([^|]+?)\s*\|\s*(.*?)\s*\|\s*$/u);
    if (!match) continue;
    const field = match[1].trim();
    const value = match[2].trim();
    if (!field || /^-+$/u.test(field) || field === 'Field') continue;
    metadata.set(field, value);
  }
  return metadata;
}

function extractSection(source, heading) {
  const pattern = new RegExp(`^## ${escapeRegExp(heading)}\\s*$([\\s\\S]*?)(?=^## |(?![\\s\\S]))`, 'imu');
  const match = String(source).match(pattern);
  if (!match) throw new Error(`Missing required section: ${heading}`);
  return match[1].trim();
}

function extractSectionLead(source, heading) {
  const section = extractSection(source, heading);
  const paragraphs = section
    .split(/\n\s*\n/u)
    .map((paragraph) => paragraph.replace(/^>\s?/gmu, '').replace(/\s+/gu, ' ').trim())
    .filter((paragraph) => paragraph && !paragraph.startsWith('|') && !paragraph.startsWith('```'));
  return paragraphs[0] || '';
}

function requiredField(metadata, field, relativePath) {
  const value = String(metadata.get(field) || '').trim();
  if (!value) throw new Error(`Missing Metadata field ${field} in ${relativePath}`);
  return value.replace(/^`|`$/gu, '').trim();
}

function splitList(value) {
  if (!value) return [];
  return [...new Set(String(value)
    .replaceAll('`', '')
    .split(/[,;\n]/u)
    .map((item) => item.trim())
    .filter((item) => item && item.toLowerCase() !== 'none'))];
}

function normalizeModes(value) {
  const modes = splitList(value).map((item) => item.toLowerCase());
  if (!modes.length) return ['ask', 'agent'];
  for (const mode of modes) {
    if (!['ask', 'agent'].includes(mode)) throw new Error(`Unsupported Work mode: ${mode}`);
  }
  return modes;
}

function toExtensionPath(relativePath) {
  const normalized = relativePath.split(path.sep).join('/');
  if (normalized.startsWith('../') || path.posix.isAbsolute(normalized)) {
    throw new Error(`Prompt path escapes canonical root: ${relativePath}`);
  }
  return `prompt-library/${normalized}`;
}

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : '';
if (invokedPath === import.meta.url) await main();
